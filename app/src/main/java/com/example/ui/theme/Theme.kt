private fun ColorScheme.withAmoledOverrides(): ColorScheme {
    return copy(
        background = Color.Black,
        surface = Color.Black,
        surfaceContainerLowest = Color.Black,
        surfaceContainerLow = Color(0xFF0D0E11),
        surfaceContainer = Color(0xFF14171A),
        surfaceContainerHigh = Color(0xFF1D2024),
        surfaceContainerHighest = Color(0xFF282B30)
    )
}

@Composable
fun SnapSweepTheme(
    themeMode: AppThemeMode = AppThemeMode.SYSTEM,
    pureBlackAmoled: Boolean = false,
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit
) {
    val context = LocalContext.current
    val systemInDark = isSystemInDarkTheme()

    val isDark = when (themeMode) {
        AppThemeMode.SYSTEM -> systemInDark
        AppThemeMode.LIGHT -> false
        AppThemeMode.DARK -> true
    }

    val baseColorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            if (isDark) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        isDark -> DarkColorScheme
        else -> LightColorScheme
    }

    val finalColorScheme = if (isDark && pureBlackAmoled) {
        baseColorScheme.withAmoledOverrides()
    } else {
        baseColorScheme
    }

    MaterialTheme(
        colorScheme = finalColorScheme,
        typography = Typography,
        content = content
    )
}
